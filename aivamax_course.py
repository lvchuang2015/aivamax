def _lesson_block(number: int, title: str, goal: str, teaching: str, demo: str, exercise: str, homework: str) -> str:
    return f"""## 课时 {number}: {title}
- 目标: {goal}
- 讲法: {teaching}
- 演示: {demo}
- 练习: {exercise}
- 课后作业: {homework}
- 讲师提醒: 先让学员说判断依据，再给标准答案，避免只背步骤。
- 常见误区: 把课程当成动作清单，忽略账号状态、内容相关性和风险记录。
- 交付物: 学员必须留下可复盘的表格或结论。
"""


