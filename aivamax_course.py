from __future__ import annotations


def markdown_list(items: list[str]) -> str:
    return "\n".join(f"- {item}" for item in items)


def daily_table(rows: list[dict]) -> str:
    lines = ["| 日期 | 教学目标 | 学员动作 | 执行上限 | 观察指标 | 交付物 |", "|---|---|---|---|---|---|"]
    for row in rows:
        lines.append(
            f"| {row.get('day', '')} | {row.get('goal', '')} | {row.get('actions', '')} | "
            f"{row.get('limit', '')} | {row.get('observe', '')} | {row.get('output', '')} |"
        )
    return "\n".join(lines)


def daily_teaching_notes(rows: list[dict]) -> str:
    blocks: list[str] = []
    for row in rows:
        blocks.append(
            f"### {row.get('day', '')}: {row.get('goal', '')}\n"
            f"- 课堂讲法: 先解释这一天的目标，再让学员判断哪些动作应该保持保守，哪些信息必须记录。\n"
            f"- 执行动作: {row.get('actions', '')}\n"
            f"- 上限边界: {row.get('limit', '')}\n"
            f"- 观察重点: {row.get('observe', '')}\n"
            f"- 当日作业: {row.get('output', '')}\n"
        )
    return "\n".join(blocks)


